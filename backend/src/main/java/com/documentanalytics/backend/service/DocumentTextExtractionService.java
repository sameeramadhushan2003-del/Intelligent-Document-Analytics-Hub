
package com.documentanalytics.backend.service;

import com.documentanalytics.backend.entity.Document;

import org.apache.pdfbox.Loader;
import org.apache.pdfbox.pdmodel.PDDocument;
import org.apache.pdfbox.text.PDFTextStripper;

import org.apache.poi.xwpf.extractor.XWPFWordExtractor;
import org.apache.poi.xwpf.usermodel.XWPFDocument;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.io.ByteArrayInputStream;
import java.io.IOException;

import java.nio.ByteBuffer;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;

import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;

import java.util.UUID;

@Service
public class DocumentTextExtractionService {

    private static final long MAX_FILE_BYTES =
            10L * 1024 * 1024;

    private static final int MAX_TEXT_CHARACTERS =
            2_000_000;

    private final Path storageRoot;

    public DocumentTextExtractionService(
            @Value("${app.storage.root}") String storageDirectory
    ) {
        this.storageRoot = Path.of(storageDirectory)
                .toAbsolutePath()
                .normalize();
    }

    public String extractText(Document document)
            throws IOException {

        if (document == null) {
            throw new IllegalArgumentException(
                    "Document cannot be null."
            );
        }

        String storageKey = document.getStorageKey();

        // Only allow the UUID storage keys generated by our backend.
        if (storageKey == null) {
            throw new IllegalArgumentException(
                    "Document has no storage key."
            );
        }

        String validatedKey =
                UUID.fromString(storageKey).toString();

        if (!validatedKey.equals(storageKey)) {
            throw new IllegalArgumentException(
                    "Invalid document storage key."
            );
        }

        Path filePath = storageRoot
                .resolve(validatedKey)
                .normalize();

        if (!filePath.getParent().equals(storageRoot)) {
            throw new IOException(
                    "Invalid document storage path."
            );
        }

        if (!Files.isRegularFile(
                filePath,
                LinkOption.NOFOLLOW_LINKS
        )) {
            throw new IOException(
                    "Stored document file was not found."
            );
        }

        long fileSize = Files.size(filePath);

        if (fileSize <= 0 || fileSize > MAX_FILE_BYTES) {
            throw new IOException(
                    "Stored document has an invalid size."
            );
        }

        byte[] fileBytes = Files.readAllBytes(filePath);

        if (fileBytes.length > MAX_FILE_BYTES) {
            throw new IOException(
                    "Stored document exceeds size limit."
            );
        }

        String contentType = document.getContentType();

        if (contentType == null) {
            throw new IOException(
                    "Document content type is missing."
            );
        }

        String extractedText;

        switch (contentType) {

            case "application/pdf" ->
                    extractedText = extractPdf(fileBytes);

            case "application/vnd.openxmlformats-officedocument.wordprocessingml.document" ->
                    extractedText = extractDocx(fileBytes);

            case "text/plain" ->
                    extractedText = extractTxt(fileBytes);

            default -> throw new IOException(
                    "Unsupported document content type."
            );
        }

        if (extractedText == null
                || extractedText.isBlank()) {

            throw new IOException(
                    "No readable text was found in the document."
            );
        }

        if (extractedText.length() > MAX_TEXT_CHARACTERS) {
            throw new IOException(
                    "Extracted text exceeds the supported limit."
            );
        }

        return extractedText
                .replace("\r\n", "\n")
                .trim();
    }

    // Extract text from text-based PDF documents.
    private String extractPdf(byte[] fileBytes)
            throws IOException {

        try (PDDocument pdf = Loader.loadPDF(fileBytes)) {

            PDFTextStripper stripper =
                    new PDFTextStripper();

            return stripper.getText(pdf);
        }
    }

    // Extract text from Microsoft Word DOCX files.
    private String extractDocx(byte[] fileBytes)
            throws IOException {

        try (
            XWPFWordExtractor extractor =
                    new XWPFWordExtractor(
                            new XWPFDocument(
                                    new ByteArrayInputStream(fileBytes)
                            )
                    )
        ) {
            return extractor.getText();
        }
    }

    // Extract UTF-8 text from TXT documents.
    private String extractTxt(byte[] fileBytes)
            throws IOException {

        var decoder = StandardCharsets.UTF_8
                .newDecoder()
                .onMalformedInput(CodingErrorAction.REPORT)
                .onUnmappableCharacter(CodingErrorAction.REPORT);

        return decoder.decode(
                ByteBuffer.wrap(fileBytes)
        ).toString();
    }
}
