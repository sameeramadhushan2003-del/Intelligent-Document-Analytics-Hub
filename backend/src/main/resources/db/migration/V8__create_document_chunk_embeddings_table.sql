
-- V8: Store AI embeddings for document chunks.
-- Intelligent Document Analytics Hub

CREATE TABLE document_chunk_embeddings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    chunk_id BIGINT NOT NULL
        REFERENCES document_chunks(id) ON DELETE CASCADE,

    embedding_model VARCHAR(120) NOT NULL,

    embedding_dimensions INTEGER NOT NULL,

    embedding vector NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_chunk_embedding_model
        UNIQUE (chunk_id, embedding_model),

    CONSTRAINT chk_embedding_model_not_blank
        CHECK (LENGTH(TRIM(embedding_model)) > 0),

    CONSTRAINT chk_embedding_dimensions
        CHECK (
            embedding_dimensions > 0
            AND vector_dims(embedding) = embedding_dimensions
        )
);
