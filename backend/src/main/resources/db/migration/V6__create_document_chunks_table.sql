CREATE TABLE document_chunks (

    -- Unique identifier for each chunk
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    -- Reference to the extracted document
    document_id BIGINT NOT NULL,

    -- Chunk order: 0, 1, 2, 3, ...
    chunk_index INTEGER NOT NULL,

    -- Actual chunk content
    chunk_text TEXT NOT NULL,

    -- Starting position in extracted text
    -- Inclusive, zero-based offset
    start_offset INTEGER NOT NULL,

    -- Ending position in extracted text
    -- Exclusive offset
    end_offset INTEGER NOT NULL,

    -- Time the chunk was created
    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    -- Each chunk belongs to an extracted document
    CONSTRAINT fk_document_chunks_extraction
        FOREIGN KEY (document_id)
        REFERENCES document_extractions(document_id)
        ON DELETE CASCADE,

    -- Prevent duplicate chunk positions
    CONSTRAINT uq_document_chunks_document_index
        UNIQUE (document_id, chunk_index),

    -- Chunk positions must start at zero or above
    CONSTRAINT chk_document_chunks_index
        CHECK (chunk_index >= 0),

    -- Validate start and end offsets
    CONSTRAINT chk_document_chunks_offsets
        CHECK (
            start_offset >= 0
            AND end_offset > start_offset
        ),

    -- Prevent empty chunk content
    CONSTRAINT chk_document_chunks_text
        CHECK (length(btrim(chunk_text)) > 0)
);
